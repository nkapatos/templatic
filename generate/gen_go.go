const genGoHeader = "// Code generated by templatic generate. DO NOT EDIT.\n"

const templaticImport = "github.com/nkapatos/templatic"

type goSig struct {
	name   string
	params []goParam
}

type goParam struct{ name, typ string }

func parseComponentSig(expr string) (goSig, error) {
	sig := strings.TrimSpace(strings.TrimPrefix(strings.TrimSpace(expr), "templ"))
	if strings.HasPrefix(sig, "(") {
		return goSig{}, errors.New("method components are not supported here")
	}
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "", "package p\nfunc "+sig+" {}\n", 0)
	if err != nil {
		return goSig{}, fmt.Errorf("component signature %q: %w", sig, err)
	}
	fd := f.Decls[0].(*ast.FuncDecl)
	if fd.Type.TypeParams != nil {
		return goSig{}, errors.New("generic components are not supported here")
	}
	src := "package p\nfunc " + sig + " {}\n"
	out := goSig{name: fd.Name.Name}
	for i, field := range fd.Type.Params.List {
		typ := src[fset.Position(field.Type.Pos()).Offset:fset.Position(field.Type.End()).Offset]
		if len(field.Names) == 0 {
			out.params = append(out.params, goParam{name: "p" + strconv.Itoa(i), typ: typ})
		}
		for _, n := range field.Names {
			out.params = append(out.params, goParam{name: n.Name, typ: typ})
		}
	}
	return out, nil
}

func islandConstructor(isl Island, sig goSig) (string, error) {
	props := ""
	for _, p := range sig.params {
		if p.typ == isl.PropsType {
			props = p.name
			break
		}
	}
	if props == "" {
		return "", fmt.Errorf("%s: no parameter of the props type %s", isl.Component, isl.PropsType)
	}
	var decl, call []string
	for _, p := range sig.params {
		decl = append(decl, p.name+" "+p.typ)
		if strings.HasPrefix(p.typ, "...") {
			call = append(call, p.name+"...")
		} else {
			call = append(call, p.name)
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// %sIsland renders %s as the %s island.\n", sig.name, sig.name, isl.Tag)
	fmt.Fprintf(&b, "func %sIsland(%s) templ.Component {\n", sig.name, strings.Join(decl, ", "))
	fmt.Fprintf(&b, "\treturn ui.Island(%q, %s, %s(%s))\n}\n", isl.Tag, props, sig.name, strings.Join(call, ", "))
	return b.String(), nil
}

type genPkg struct {
	path string
	sels []string
}

var genPkgs = map[string]genPkg{
	"templ":     {"github.com/a-h/templ", []string{"Component"}},
	"ui":        {templaticImport + "/ui", []string{"Island"}},
	"live":      {templaticImport + "/live", []string{"DeclareSessionRegion"}},
	"templatic": {templaticImport, nil},
}

func (g genPkg) emits(sel string) bool { return g.sels == nil || slices.Contains(g.sels, sel) }

type qualScan struct {
	user     map[string]bool
	gen      map[string]bool
	genAt    []int
	declared map[string]bool
	base     int
}

func (q *qualScan) scan(n ast.Node, user bool) {
	if n == nil {
		return
	}
	ast.Inspect(n, func(c ast.Node) bool {
		switch c := c.(type) {
		case *ast.FuncType:
			if c.Params != nil {
				for _, f := range c.Params.List {
					for _, nm := range f.Names {
						q.declared[nm.Name] = true
					}
				}
				q.scan(c.Params, true)
			}
			if c.Results != nil {
				q.scan(c.Results, user)
			}
			return false
		case *ast.StructType:
			q.scan(c.Fields, true)
			return false
		case *ast.IndexExpr:
			q.scan(c.X, user)
			q.scan(c.Index, true)
			return false
		case *ast.CallExpr:
			if !user && q.generated(c.Fun) {
				q.scan(c.Fun, user)
				for _, a := range c.Args {
					q.scan(a, true)
				}
				return false
			}
		case *ast.SelectorExpr:
			id, ok := c.X.(*ast.Ident)
			if !ok {
				return true
			}
			if g, ok := genPkgs[id.Name]; ok && !user && g.emits(c.Sel.Name) {
				q.gen[id.Name] = true
				q.genAt = append(q.genAt, int(id.Pos())-q.base)
			} else {
				q.user[id.Name] = true
			}
			return false
		}
		return true
	})
}

func (q *qualScan) generated(e ast.Expr) bool {
	if ix, ok := e.(*ast.IndexExpr); ok {
		e = ix.X
	}
	sel, ok := e.(*ast.SelectorExpr)
	if !ok {
		return false
	}
	id, ok := sel.X.(*ast.Ident)
	if !ok {
		return false
	}
	g, ok := genPkgs[id.Name]
	return ok && g.emits(sel.Sel.Name)
}

func scanQualifiers(body string) (*qualScan, error) {
	const prefix = "package p\n"
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "", prefix+body, parser.SkipObjectResolution)
	if err != nil {
		return nil, fmt.Errorf("generated Go does not parse: %w", err)
	}
	q := &qualScan{
		user: map[string]bool{}, gen: map[string]bool{}, declared: map[string]bool{},
		base: fset.File(f.Pos()).Base() + len(prefix),
	}
	for _, d := range f.Decls {
		q.scan(d, false)
	}
	return q, nil
}

type goImport struct{ name, path string }

var (
	versionElem   = regexp.MustCompile(`^v[0-9]+$`)
	versionSuffix = regexp.MustCompile(`\.v[0-9]+$`)
)

func (im goImport) candidates() []string {
	if im.name != "" {
		return []string{im.name}
	}
	elems := strings.Split(im.path, "/")
	last := elems[len(elems)-1]
	if len(elems) > 1 && versionElem.MatchString(last) {
		last = elems[len(elems)-2]
	}
	last = versionSuffix.ReplaceAllString(last, "")
	out := []string{last}
	for _, c := range []string{strings.TrimPrefix(last, "go-"), strings.TrimSuffix(last, "-go")} {
		c = strings.NewReplacer("-", "_", ".", "_").Replace(c)
		if !slices.Contains(out, c) {
			out = append(out, c)
		}
	}
	return out
}

func aliasGenerated(body string, offs []int, alias map[string]string) string {
	src := []byte(body)
	offs = slices.Sorted(slices.Values(offs))
	for i := len(offs) - 1; i >= 0; i-- {
		o, j := offs[i], offs[i]
		for j < len(src) && (src[j] == '_' || src[j] >= '0' && src[j] <= '9' || src[j]|0x20 >= 'a' && src[j]|0x20 <= 'z') {
			j++
		}
		if a, ok := alias[string(src[o:j])]; ok {
			src = append(src[:o:o], append([]byte(a), src[j:]...)...)
		}
	}
	return string(src)
}

func writeGenGo(path string, templGo []byte, decls []string) (wrote bool, unresolved []string, err error) {
	if len(decls) == 0 {
		old, err := os.ReadFile(path)
		if err == nil && bytes.HasPrefix(old, []byte(genGoHeader)) {
			return false, nil, os.Remove(path)
		}
		return false, nil, nil
	}
	fset := token.NewFileSet()
	tf, err := parser.ParseFile(fset, "", templGo, parser.ImportsOnly)
	if err != nil {
		return false, nil, err
	}
	body := strings.Join(decls, "\n")
	q, err := scanQualifiers(body)
	if err != nil {
		return false, nil, err
	}

	var userImps []goImport
	for _, is := range tf.Imports {
		p, _ := strconv.Unquote(is.Path.Value)
		im := goImport{path: p}
		if is.Name != nil {
			im.name = is.Name.Name
		}
		userImps = append(userImps, im)
	}

	taken := map[string]bool{}
	for _, m := range []map[string]bool{q.user, q.declared} {
		maps.Copy(taken, m)
	}
	for _, im := range userImps {
		for _, c := range im.candidates() {
			taken[c] = true
		}
	}
	alias := map[string]string{}
	local := map[string]string{}
	for _, n := range slices.Sorted(maps.Keys(q.gen)) {
		local[n] = n
		if q.user[n] || q.declared[n] {
			a := "tc" + n
			for taken[a] {
				a += "_"
			}
			taken[a] = true
			alias[n], local[n] = a, a
		}
	}
	if len(alias) > 0 {
		body = aliasGenerated(body, q.genAt, alias)
		if q, err = scanQualifiers(body); err != nil {
			return false, nil, err
		}
	}

	// Claimed qualifiers are bound by the generated imports; a user import of a generated path is that import.
	claimed := map[string]bool{}
	var imps []goImport
	for _, n := range slices.Sorted(maps.Keys(local)) {
		im := goImport{path: genPkgs[n].path}
		if local[n] != n {
			im.name = local[n]
		}
		imps = append(imps, im)
		claimed[local[n]] = true
	}
	var unmatched []goImport
	seen := map[goImport]bool{}
	for _, im := range userImps {
		if im.name == "_" || im.name == "." || seen[im] {
			continue
		}
		seen[im] = true
		matched := false
		for _, c := range im.candidates() {
			if q.user[c] && !claimed[c] {
				claimed[c] = true
				matched = true
				imps = append(imps, im)
				break
			}
		}
		if !matched && !isGenPath(im.path) {
			unmatched = append(unmatched, im)
		}
	}
	missing := false
	for n := range q.user {
		missing = missing || !claimed[n]
	}
	if missing && len(unmatched) > 0 {
		names := packageNames(filepath.Dir(path), unmatched)
		for _, im := range unmatched {
			if n := names[im.path]; n != "" && q.user[n] && !claimed[n] {
				claimed[n] = true
				imps = append(imps, im)
			}
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, "%s\npackage %s\n\nimport (\n", genGoHeader, tf.Name.Name)
	for _, im := range imps {
		if im.name != "" {
			fmt.Fprintf(&b, "\t%s %q\n", im.name, im.path)
		} else {
			fmt.Fprintf(&b, "\t%q\n", im.path)
		}
	}
	b.WriteString(")\n\n")
	b.WriteString(body)
	out, err := format.Source([]byte(b.String()))
	if err != nil {
		return false, nil, fmt.Errorf("generated Go does not format: %w", err)
	}
	dot := false
	for _, im := range userImps {
		dot = dot || im.name == "."
	}
	for _, n := range slices.Sorted(maps.Keys(q.user)) {
		if !claimed[n] && !q.declared[n] && !dot {
			unresolved = append(unresolved, n)
		}
	}
	return true, unresolved, writeAtomic(path, out)
}

type unresolvedQuals struct {
	rel     string
	genPath string
	names   []string
}

// checkUnresolved names a qualifier that is neither imported nor declared, rather than "undefined: x" at go build.
// It runs after every _templ.go is written because a name may come from another .templ file.
func checkUnresolved(pending []unresolvedQuals) error {
	top := map[string]map[string]bool{}
	for _, u := range pending {
		dir := filepath.Dir(u.genPath)
		names, ok := top[dir]
		if !ok {
			var err error
			if names, err = topLevelNames(dir); err != nil {
				return err
			}
			top[dir] = names
		}
		var bad []string
		for _, n := range u.names {
			if !names[n] {
				bad = append(bad, n)
			}
		}
		if len(bad) > 0 {
			return fmt.Errorf("%s: %s used in a generated declaration (a component signature or pragma) but not imported by the file, nor declared in its package: add the import to the .templ file",
				u.rel, strings.Join(bad, ", "))
		}
	}
	return nil
}

// topLevelNames skips a file that does not parse; go build reports it.
func topLevelNames(dir string) (map[string]bool, error) {
	files, err := filesWithSuffix(dir, ".go")
	if err != nil {
		return nil, err
	}
	names := map[string]bool{}
	fset := token.NewFileSet()
	for _, name := range files {
		if strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.SkipObjectResolution)
		if err != nil {
			continue
		}
		for _, d := range f.Decls {
			switch d := d.(type) {
			case *ast.FuncDecl:
				if d.Recv == nil {
					names[d.Name.Name] = true
				}
			case *ast.GenDecl:
				for _, sp := range d.Specs {
					switch sp := sp.(type) {
					case *ast.ValueSpec:
						for _, n := range sp.Names {
							names[n.Name] = true
						}
					case *ast.TypeSpec:
						names[sp.Name.Name] = true
					}
				}
			}
		}
	}
	return names, nil
}

// filesWithSuffix treats dir literally, unlike filepath.Glob, so '[' or '*' in a path works.
func filesWithSuffix(dir, suffix string) ([]string, error) {
	ents, err := os.ReadDir(dir)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var out []string
	for _, e := range ents {
		if !e.IsDir() && strings.HasSuffix(e.Name(), suffix) {
			out = append(out, e.Name())
		}
	}
	return out, nil
}

func packageNames(dir string, imps []goImport) map[string]string {
	args := []string{"list", "-e", "-f", "{{.ImportPath}} {{.Name}}", "--"}
	for _, im := range imps {
		args = append(args, im.path)
	}
	cmd := exec.Command("go", args...)
	cmd.Dir = dir
	out, _ := cmd.Output()
	names := map[string]string{}
	for _, line := range strings.Split(string(out), "\n") {
		if p, n, ok := strings.Cut(line, " "); ok {
			names[p] = n
		}
	}
	return names
}

func isGenPath(p string) bool {
	for _, g := range genPkgs {
		if g.path == p {
			return true
		}
	}
	return false
}
